function offsetDate(days) {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
}

function offsetIso(hoursAgo) {
  const d = new Date(Date.now() - hoursAgo * 3600000);
  return d.toISOString();
}

